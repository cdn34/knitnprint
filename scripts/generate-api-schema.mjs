import { readFile, writeFile } from 'node:fs/promises'

const input = new URL('../openapi/knitprint.json', import.meta.url)
const output = new URL('../packages/api-client/src/schema.ts', import.meta.url)
const document = JSON.parse(await readFile(input, 'utf8'))
const schemas = document.components?.schemas ?? {}

function typeFor(schema) {
  if (schema.$ref) return schema.$ref.split('/').at(-1)
  if (schema.type === 'array') return `Array<${typeFor(schema.items)}>`
  if (schema.type === 'string') return schema.enum?.map(JSON.stringify).join(' | ') ?? 'string'
  if (schema.type === 'integer' || schema.type === 'number') return 'number'
  if (schema.type === 'boolean') return 'boolean'
  if (schema.type === 'object') {
    const required = new Set(schema.required ?? [])
    const fields = Object.entries(schema.properties ?? {}).map(
      ([name, value]) =>
        `  ${JSON.stringify(name)}${required.has(name) ? '' : '?'}: ${typeFor(value)}`,
    )
    return `{\n${fields.join('\n')}\n}`
  }
  return 'unknown'
}

const declarations = Object.entries(schemas)
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([name, schema]) => `export interface ${name} ${typeFor(schema)}`)
  .join('\n\n')

const source = `// Generated by scripts/generate-api-schema.mjs. Do not edit manually.\n\n${declarations}\n`
await writeFile(output, source)
console.log(`wrote ${output.pathname}`)


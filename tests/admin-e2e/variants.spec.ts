test('uses the approved size and color controls, combined rows and customer preview without changing variant identities', async ({ page }, testInfo) => {
  expect((await page.request.post('/api/admin/auth/login', { data: { email, password } })).ok()).toBe(true)
  const title = `Reference design ${Date.now()}`
  const created = await page.request.post('/api/admin/products', { data: { title, slug: title.toLowerCase().replaceAll(' ', '-'), variants: [{ title: 'Default', price_minor: 4000, currency: 'EUR', available_quantity: 3 }] } })
  expect(created.status()).toBe(201)
  const product = await created.json()
  await page.goto('/#products')
  await page.getByRole('article').filter({ hasText: title }).getByRole('button', { name: 'Edit', exact: true }).click()
  const matrix = page.locator('.variant-matrix')
  await expect(matrix.getByRole('heading', { name: 'Tamanhos e cores', exact: true })).toBeVisible()
  await matrix.getByLabel('Tem tamanhos', { exact: true }).check()
  await matrix.getByLabel('Tem cores', { exact: true }).check()
  for (const size of ['XS', 'L', 'XL', 'XXL']) await matrix.getByRole('checkbox', { name: `Size: ${size}`, exact: true }).uncheck()
  for (const color of ['Black', 'Red', 'Green', 'Blue', 'Yellow', 'Grey']) await matrix.getByRole('checkbox', { name: `Color: ${color}`, exact: true }).uncheck()
  await matrix.getByText('Associar o stock existente às opções (opcional)', { exact: true }).click()
  await matrix.getByLabel('Associar Color 1', { exact: true }).selectOption('PNK')
  await matrix.getByLabel('Associar Size 1', { exact: true }).selectOption('S')
  await matrix.getByRole('button', { name: 'Gerar 4 variantes', exact: true }).click()
  await expect(matrix.locator('.matrix-scroll tbody tr')).toHaveCount(4)
  await expect(matrix.getByRole('columnheader', { name: 'Variante', exact: true })).toBeVisible()
  await expect(matrix.locator('.variant-cell-value')).toContainText(['White · S', 'Pink · S', 'White · M', 'Pink · M'])
  await expect(matrix.locator('.variant-formatted-price').first()).toContainText('40,00')
  await matrix.getByLabel('Definir preços diferentes por variante', { exact: true }).check()
  await matrix.getByLabel('Preço 1', { exact: true }).fill('42.50')
  await matrix.getByLabel('Stock 1', { exact: true }).fill('2')
  await matrix.getByLabel('Definir preços diferentes por variante', { exact: true }).uncheck()
  await expect(matrix.locator('.variant-formatted-price').first()).toContainText('42,50')
  await matrix.getByLabel('Novo tamanho', { exact: true }).fill('2 anos')
  await matrix.getByRole('button', { name: 'Adicionar tamanho', exact: true }).click()
  await matrix.getByLabel('Nome da nova cor', { exact: true }).fill('Ocre')
  await matrix.getByRole('button', { name: 'Adicionar cor', exact: true }).click()
  await matrix.getByRole('button', { name: 'Gerar 9 variantes', exact: true }).click()
  await expect(matrix.locator('.matrix-scroll tbody tr')).toHaveCount(9)
  await matrix.getByLabel('Ativar combinação 9', { exact: true }).uncheck()
  await expect(matrix.locator('.matrix-scroll tbody tr')).toHaveCount(9)
  await expect(matrix.locator('.matrix-scroll tbody tr').last()).toContainText('Desativada')
  await matrix.getByLabel('Ativar combinação 9', { exact: true }).check()
  await matrix.screenshot({ path: testInfo.outputPath('reference-admin.png') })
  await matrix.getByRole('tab', { name: 'Como fica na loja', exact: true }).click()
  await matrix.locator('.variant-shop-choices').getByRole('button', { name: 'Pink', exact: true }).click()
  await expect(matrix.locator('.variant-shop-selection')).toHaveText('Pink · S')
  await expect(matrix.locator('.variant-preview-stock')).toContainText('3 em stock')
  await matrix.screenshot({ path: testInfo.outputPath('reference-customer-preview.png') })
  await Promise.all([
    page.waitForResponse(result => result.url().endsWith('/variant-matrix') && result.request().method() === 'PUT' && result.ok()),
    matrix.getByRole('button', { name: 'Guardar opções e variantes' }).click(),
  ])
  const saved = await (await page.request.get(`/api/admin/products/${product.id}`)).json()
  const original = saved.variants.find((variant: { id: string }) => variant.id === product.variants[0].id)
  expect(original.sku).toBe(product.variants[0].sku)
  expect(original.available_quantity).toBe(3)
  expect(saved.variants.filter((variant: { retired: boolean }) => !variant.retired)).toHaveLength(9)
})

test('copies templates, maps existing stock, and sells a generated color/size combination', async ({ page }) => {
  expect((await page.request.post('/api/admin/auth/login', { data: { email, password } })).ok()).toBe(true)
  const slug = `variant-shirt-${Date.now()}`
  const response = await page.request.post('/api/admin/products', { data: { title: slug, slug, variants: [{ title: 'Default', price_minor: 2000, currency: 'EUR', available_quantity: 3 }] } })
  expect(response.status()).toBe(201)
  const product = await response.json()
  await page.goto('/#products')
  await page.getByRole('article').filter({ hasText: slug }).getByRole('button', { name: 'Edit', exact: true }).click()
  const matrix = page.locator('.variant-matrix')
  await expect(matrix).toContainText(product.sku)
  await matrix.getByText('Modelos e outras opções', { exact: true }).click()
  await matrix.getByRole('button', { name: 'Adicionar opção Color', exact: true }).click()
  await expect(matrix.getByLabel('Usar fotografias específicas por cor (opcional)')).not.toBeChecked()
  for (const color of ['Black', 'White', 'Green', 'Yellow', 'Pink', 'Grey']) await matrix.getByRole('checkbox', { name: `Color: ${color}`, exact: true }).uncheck()
  await matrix.getByRole('button', { name: 'Adicionar opção Size', exact: true }).click()
  await matrix.getByText('Associar o stock existente às opções (opcional)', { exact: true }).click()
  await matrix.getByLabel('Associar Color 1', { exact: true }).selectOption('RED')
  await matrix.getByLabel('Associar Size 1', { exact: true }).selectOption('M')
  await matrix.getByRole('button', { name: 'Gerar 12 variantes', exact: true }).click()
  await expect(matrix.locator('.variant-stock-total')).toContainText('12 variantes')
  await matrix.getByText('Opções avançadas das combinações', { exact: true }).click()
  await matrix.getByText('Aplicar preço ou stock em lote', { exact: true }).click()
  await matrix.getByLabel('Preço para todas (€)', { exact: true }).fill('22.50')
  await expect(matrix.locator('.variant-row-state.backorder')).not.toHaveCount(0)
  await expect(matrix.locator('.variant-row-state.backorder').first()).toHaveText('Por encomenda')
  await matrix.getByLabel('Mostrar referências', { exact: true }).check()
  await expect(matrix.locator('.matrix-scroll')).toContainText(product.variants[0].sku)
  expect((await new AxeBuilder({ page }).include('.variant-matrix').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()).violations).toEqual([])
  await Promise.all([
    page.waitForResponse(r => r.url().endsWith('/variant-matrix') && r.request().method() === 'PUT' && r.ok()),
    matrix.getByRole('button', { name: 'Guardar opções e variantes' }).click(),
  ])
  const saved = await (await page.request.get(`/api/admin/products/${product.id}`)).json()
  expect(saved.variants).toHaveLength(12)
  expect(saved.variants.find((v: { id: string }) => v.id === product.variants[0].id).sku).toBe(product.variants[0].sku)
  expect(saved.variants.find((v: { id: string }) => v.id === product.variants[0].id).available_quantity).toBe(3)
  expect(saved.variants.every((v: { sku: string; price_minor: number }) => v.sku.startsWith(saved.sku) && v.price_minor === 2250)).toBe(true)
  // The shared palette is unaffected by this product's removals.
  const templates = await (await page.request.get('/api/admin/variant-templates')).json()
  expect(templates[0].definition.values).toHaveLength(8)
  expect((await page.request.post(`/api/admin/products/${product.id}/status`, { data: { status: 'active' } })).ok()).toBe(true)
  const redM = saved.variants.find((v: { selections: {COL: string; SIZ: string} }) => v.selections.COL === 'RED' && v.selections.SIZ === 'M')
  const blueM = saved.variants.find((v: { selections: {COL: string; SIZ: string} }) => v.selections.COL === 'BLU' && v.selections.SIZ === 'M')
  await signInVerifiedCustomer(page.request, `${slug}@example.test`, 'Variant', 'Tester')
  await page.goto(`${storefrontUrl}/products/${slug}`)
  const picker = page.locator('.structured-variant-picker')
  await picker.getByRole('button', { name: 'Red', exact: true }).click()
  await picker.getByRole('button', { name: 'M', exact: true }).click()
  await expect(picker.getByRole('button', { name: 'M', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await picker.getByRole('button', { name: 'Blue', exact: true }).click()
  await expect(picker.getByRole('button', { name: 'Blue', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(picker.getByRole('button', { name: 'M', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const added = page.waitForResponse(r => r.url().endsWith('/api/cart/items') && r.request().method() === 'POST')
  await page.getByRole('button', { name: /Add to (bag|cart)/i }).click()
  const addedResponse = await added
  expect(addedResponse.status()).toBe(201)
  expect(addedResponse.request().postDataJSON().variant_id).toBe(blueM.id)
  const cart = await (await page.request.get(`${storefrontUrl}/api/cart`)).json()
  expect(cart.items.some((item: {variant_id: string}) => item.variant_id === blueM.id)).toBe(true)
  expect(redM.id).toBe(product.variants[0].id)
})

